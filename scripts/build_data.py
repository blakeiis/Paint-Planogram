"""Convert the raw color locator export (raw/colors.json) into data.js for the app.

Each chip: [name, code, hex, sectionKey, row, col, slot]
"""
import json, re, sys, pathlib

src = pathlib.Path(sys.argv[1])
out = pathlib.Path(sys.argv[2])
j = json.load(open(src))
D = j["data"]

def first(code):
    return (code or "").split("/")[0].strip()

chips = []
sections = []

# Core palette: 6 hue families, each with 4 bands (Pure 5 rows, others 7), 8 columns.
HUES = [("R", "Reds"), ("O", "Oranges"), ("Y", "Yellows"), ("G", "Greens"), ("B", "Blues"), ("P", "Purples")]
BANDS = [("P", "Pure", 5), ("M", "Muted", 7), ("S", "Shaded", 7), ("N", "Neutral", 7)]
core_re = re.compile(r"^([ROYGBP])([PMSN])(\d+)-(\d+)$")
for h, hname in HUES:
    for b, bname, rows in BANDS:
        sections.append({"key": h + b, "title": f"{hname} · {bname}", "group": hname, "cols": 8, "rows": rows})
for c in D["core"]:
    m = core_re.match(c["id"])
    if not m:
        print("skip core", c); continue
    chips.append([c["name"].strip(), first(c["alt"]), c["hex"], m[1] + m[2], int(m[4]), int(m[3]), c["id"]])

# Whites / Neutrals / Grays / One Coat Hide: placed row by row in list order (same as the locator site).
for s in D["sections"]:
    sections.append({"key": s["key"], "title": s["title"], "group": s["title"], "cols": s["cols"], "rows": s["rows"]})
    for i, c in enumerate(s["colors"]):
        if not c: continue
        r, col = i // s["cols"] + 1, i % s["cols"] + 1
        if s["key"] == "och":
            code, slot = first(c["alt"]), first(c["id"])
        else:
            code, slot = first(c["id"]), first(c["alt"])
        chips.append([c["name"].strip(), code, c["hex"], s["key"], r, col, slot])

# Designer Collection: 2 columns of large chips.
lookup = {}
def key(x): return re.sub(r"[^a-z0-9]", "", x.lower())
for c in [c for s in D["sections"] for c in s["colors"] if c] + D["core"]:
    for f in (c["id"], c.get("alt") or ""):
        for p in f.split("/"):
            k = key(p)
            if k and k not in lookup: lookup[k] = c
dcols = j["designerCols"]
drows = max(len(c) for c in dcols)
sections.append({"key": "dc", "title": "Designer Collection", "group": "Designer Collection", "cols": len(dcols), "rows": drows, "big": True})
for ci, col in enumerate(dcols):
    for ri, code in enumerate(col):
        m = lookup.get(key(code))
        if not m:
            print("designer missing", code); continue
        chips.append([m["name"].strip(), code, m["hex"], "dc", ri + 1, ci + 1, f"D-{ci+1}-{ri+1}"])

trending = [t["items"] for t in D["trending"]][0]
coty = next((c["alt"] for c in D["core"] if c.get("tag") == "COTY-27"), None)

data = {"sections": sections, "chips": chips, "featured": trending, "coty": coty}
out.write_text("// Generated by scripts/build_data.py. Do not edit by hand.\nwindow.WALL = " + json.dumps(data, separators=(",", ":"), ensure_ascii=False) + ";\n")
print(len(chips), "chips,", len({c[0].lower() for c in chips}), "unique names,", len(sections), "sections")
